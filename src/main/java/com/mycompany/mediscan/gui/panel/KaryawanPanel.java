        K.setIdKaryawan(txtKRID.getText());
        K.setNamaLengkap(txtKRName.getText());
        K.setDepartemen(txtKRDept.getSelectedItem().toString());
        KaryawanService service = new KaryawanService();
        service.updateKaryawan(K);
